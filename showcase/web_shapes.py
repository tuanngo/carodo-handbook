#!/usr/bin/env python3
"""S6: the website's route shapes, from out/shapes.json (simplified, unit-box, no coordinate).

    python3 showcase/web_shapes.py > ../carodo-app/apps/web/src/components/site/route-shapes.ts

Fits each chosen shape into the box its illustration draws it in (carodo-app
apps/web/src/components/site/feature-art.tsx), optionally turned on its side, and writes SVG path
data plus the points the art places things at (the ends, the car at a share of the way). Only
panel-space numbers come out: nothing maps back to a place. Standard library only.
"""

import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent

# id → (box x, y, width, height, turn: 0, or -90 for a quarter counterclockwise, the car's share of the way)
SHAPES = {
    "prenn": ("prenn", (40, 70, 330, 120), -90, 0.6),
    "maPiLeng": ("ma-pi-leng", (30, 30, 340, 170), -90, 0.58),
    "haiVan": ("hai-van", (40, 100, 80, 132), 0, 0.5),
}


def fit(points, box, turn):
    if turn == -90:  # a quarter counterclockwise in a y-down box: (x, y) → (y, 1 - x)
        points = [(y, 1 - x) for x, y in points]
    xs, ys = [p[0] for p in points], [p[1] for p in points]
    w, h = max(xs) - min(xs), max(ys) - min(ys)
    bx, by, bw, bh = box
    k = min(bw / w, bh / h)
    ox = bx + (bw - w * k) / 2
    oy = by + (bh - h * k) / 2
    return [((x - min(xs)) * k + ox, (y - min(ys)) * k + oy) for x, y in points]


def at_share(points, share):
    seg = [math.dist(a, b) for a, b in zip(points, points[1:])]
    target = sum(seg) * share
    for (a, b), d in zip(zip(points, points[1:]), seg):
        if target <= d:
            f = target / d if d else 0
            return (a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f)
        target -= d
    return points[-1]


def fmt(p):
    return f"{p[0]:.1f} {p[1]:.1f}"


def main():
    shapes = json.loads((HERE / "out" / "shapes.json").read_text())["shapes"]
    out = [
        "// Generated by carodo-handbook showcase/web_shapes.py from its generated drives' shapes; do not edit.",
        "// Real road shapes (© OpenStreetMap contributors), simplified and fitted to each illustration's",
        "// panel: SVG units only, nothing that maps back to a place.",
        "",
        "export type RouteShape = { d: string; start: [number, number]; end: [number, number]; car: [number, number] };",
        "",
    ]
    for name, (source, box, turn, share) in SHAPES.items():
        pts = fit([tuple(p) for p in shapes[source]["points"]], box, turn)
        d = "M" + " L".join(fmt(p) for p in pts)
        car = at_share(pts, share)
        r = lambda v: round(v, 1)
        out.append(
            f"export const {name}: RouteShape = {{\n  d: \"{d}\",\n"
            f"  start: [{r(pts[0][0])}, {r(pts[0][1])}],\n  end: [{r(pts[-1][0])}, {r(pts[-1][1])}],\n"
            f"  car: [{r(car[0])}, {r(car[1])}],\n}};\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
